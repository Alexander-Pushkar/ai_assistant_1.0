def generate_phrases(n):
    phrases = []
    for i in range(n):
        base = random.choice(templates)
        variety = random.choice([
            f"{base}",
            f"{base}, это нормально?",
            f"{base} перед анализом",
            f"{base} накануне",
            f"{base} утром",
            f"{base} вчера вечером",
            f"Я принимал {base.lower()}",
            f"Случайно выпил {base.lower()}",
            f"Извините, я {base.lower()}",
            f"Можно ли, если я {base.lower()}?",
            f"Принимаю {base.lower()} постоянно",
            f"Доктор, я {base.lower()}, это не повлияет?",
        ])
        phrases.append(variety)
    return phrases

data = generate_phrases(2000)
with open("прием_лекарств_2000.csv", "w", encoding="utf-8", newline="") as f:
    writer = csv.writer(f, delimiter=";", quoting=csv.QUOTE_ALL)
    writer.writerow(["text", "label"])
    writer.writerows([[phrase, "прием_лекарств"] for phrase in data])

