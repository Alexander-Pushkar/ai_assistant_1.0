def generate_phrases(n):
    phrases = []
    for i in range(n):
        base = random.choice(templates)
        variety = random.choice([
            f"{base}",
            f"{base}, это нормально?",
            f"{base} перед анализом",
            f"{base} за час до сдачи",
            f"{base} утром",
            f"{base} натощак",
            f"{base} (я пациент)",
            f"Я {base[2:].lower()}",
            f"Случайно {base.lower()}",
            f"Извините, я {base.lower()}",
            f"Можно ли, если я {base.lower()}?",
            f"Я нарушил диету: {base.lower()}",
            f"Ой, я {base.lower()}, это плохо?",
        ])
        phrases.append(variety)
    return phrases

data = generate_phrases(2000)
with open("нарушение_диеты_2000.csv", "w", encoding="utf-8", newline="") as f:
    writer = csv.writer(f, delimiter=";", quoting=csv.QUOTE_ALL)
    writer.writerow(["text", "label"])
    writer.writerows([[phrase, "нарушение_диеты"] for phrase in data])

